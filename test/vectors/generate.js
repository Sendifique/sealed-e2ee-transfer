/**
 * test/vectors/generate.js
 *
 * Builds the format 1 test vectors from fixed inputs with the independent
 * reference implementation (reference.js) and the native argon2 package.
 *
 *     node test/vectors/generate.js     writes test/vectors/format-1.json
 *
 * test/vectors.test.js rebuilds them and fails if the stored file differs,
 * so the vectors cannot drift from the reference unnoticed.
 */

import crypto from 'node:crypto'
import fs from 'node:fs'
import { fileURLToPath } from 'node:url'
import argon2 from 'argon2'
import { readerToken, encryptFile, sealManifest, wrapKey, pattern, fixed } from './reference.js'

export const VECTORS_FILE = new URL('./format-1.json', import.meta.url)

const b64 = (buf) => Buffer.from(buf).toString('base64')

/** The files of the vectors: small ones in full, large ones by hash. */
const FILES = [
  { name: 'empty', plaintext: Buffer.alloc(0), inline: true },
  { name: 'short text', plaintext: Buffer.from('Hello from format 1. Grüße! 🔒\n', 'utf8'), inline: true },
  { name: 'exactly one full record', plaintext: pattern(65519), inline: false },
  { name: 'two records', plaintext: pattern(70000), inline: false }
]

/**
 * The vectors as a JSON-ready object.
 *
 * @returns {Promise<object>}
 */
export async function buildVectors () {
  const hash = (buf) => crypto.createHash('sha256').update(buf).digest('hex')

  const mainKey = fixed('format-1 main key', 32)
  const keychainSalt = fixed('format-1 key-chain salt', 16)

  const files = FILES.map((f, i) => {
    const salt = fixed(`format-1 file salt ${i}`, 16)
    const ciphertext = encryptFile(mainKey, salt, f.plaintext)
    const entry = {
      name: f.name,
      plaintext: f.inline
        ? { base64: b64(f.plaintext) }
        : { pattern: 'byte i = i mod 251', length: f.plaintext.length },
      salt: b64(salt),
      ciphertextLength: ciphertext.length,
      ciphertextSha256: hash(ciphertext)
    }
    if (f.inline) entry.ciphertext = b64(ciphertext)
    return entry
  })

  const manifestJson = {
    v: 1,
    subject: 'Test vectors',
    files: files.map((f, i) => ({
      i,
      name: `${f.name}.bin`,
      path: null,
      size: FILES[i].plaintext.length,
      type: 'application/octet-stream',
      salt: f.salt
    }))
  }
  const manifestIv = fixed('format-1 manifest iv', 16)
  const sealed = sealManifest(mainKey, keychainSalt, manifestJson, manifestIv)

  const password = 'correct horse battery staple'
  const kdfSalt = fixed('format-1 argon2id salt', 16)
  const params = { v: 1, alg: 'argon2id', m: 65536, t: 3, p: 1 }
  const out = await argon2.hash(password.normalize('NFC'), {
    raw: true, type: argon2.argon2id, salt: kdfSalt,
    memoryCost: params.m, timeCost: params.t, parallelism: params.p, hashLength: 64
  })
  const bindTo = 'example-v1:00000000-0000-4000-8000-000000000001'
  const wrapIv = fixed('format-1 wrap iv', 12)
  const wrapped = wrapKey(mainKey, out, wrapIv, bindTo)

  return {
    format: 1,
    note: 'Generated by test/vectors/generate.js from fixed inputs; see PROTOCOL.md. Binary values are standard base64 unless stated; mainKey is base64url as in a share link.',
    mainKey: Buffer.from(mainKey).toString('base64url'),
    keychainSalt: b64(keychainSalt),
    readerToken: b64(readerToken(mainKey, keychainSalt)),
    files,
    manifest: {
      json: manifestJson,
      iv: b64(manifestIv),
      sealed: b64(sealed)
    },
    password: {
      password,
      kdfSalt: b64(kdfSalt),
      kdfParams: params,
      bindTo,
      wrapIv: b64(wrapIv),
      passwordAuth: b64(wrapped.passwordAuth),
      passwordAuthSha256: hash(wrapped.passwordAuth),
      wrappedKey: b64(wrapped.wrappedKey)
    }
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === fs.realpathSync(process.argv[1])) {
  fs.writeFileSync(VECTORS_FILE, JSON.stringify(await buildVectors(), null, 2) + '\n')
  console.log('wrote', fileURLToPath(VECTORS_FILE))
}
